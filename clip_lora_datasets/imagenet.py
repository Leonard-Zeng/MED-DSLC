class ImageFolderWithClassnames(datasets.ImageFolder):
    def __init__(self, root, classnames_file, **kwargs):
        super().__init__(root, **kwargs)

        class_ids = []
        class_id_to_idx = {}
        with open(classnames_file) as f:
            for real_idx, line in enumerate(f.readlines()):
                parts = line.strip().split()
                if not parts:
                    continue
                class_id = parts[0]      # e.g. "n01440764"
                class_id_to_idx[class_id] = real_idx
                class_ids.append(class_id)

        # old_idx2new_idx
        old_idx2new_idx = {}
        old_idx = 0
        for class_id in sorted(os.listdir(root)):
            if os.path.isdir(os.path.join(root, class_id)):
                old_idx2new_idx[old_idx] = class_id_to_idx[class_id]
                old_idx += 1

        # 2) Remap samples: old index -> folder name -> desired label
        new_samples = []
        for path, old_idx in self.samples:
            new_idx = old_idx2new_idx[old_idx]
            new_samples.append((path, new_idx))

        self.samples = new_samples
        # For older torchvision versions that use .imgs / .targets:
        self.imgs = self.samples
        self.targets = [y for _, y in self.samples]

        # 3) Update metadata to match the txt order
        self.classes = class_ids
        self.class_to_idx = class_id_to_idx


